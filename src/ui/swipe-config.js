  // Элементы, клик по которым не должен запускать жест свайпа. setPointerCapture
  // теперь берётся не сразу на pointerdown, а только когда ось жеста уже
  // определена как горизонтальная (см. swipe-gesture.js:onPointerMove) - поэтому
  // здесь остаются только маленькие точечные controls, где даже сам факт
  // "подождать движение перед стартом слежения" может съесть первый тап
  // (play/pause плеера, кнопка "на весь экран" и т.п.). 'a' и 'video' отсюда
  // убраны: они занимают всю площадь фото/видео/кружка-вложения, и раньше
  // это полностью блокировало старт свайпа прямо на медиа (работал только на
  // пустом поле строки рядом с пузырём) - см. riedchat bug report, п.2.
  INTERACTIVE_SEL: '.voice-play, .track-play, .track-download, .track-bar, ' +
    '.media-expand-btn, .video-tap-load, button, input, textarea',
