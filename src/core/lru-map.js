// ===================== core/lru-map.js =====================
// Крошечная обёртка над Map с верхней границей размера и LRU-эвикцией.
// Несколько in-memory кэшей в приложении (постеры видео, распарсенные
// голосовые файлы, пики волны) были обычными Map без ограничения размера/TTL -
// на обычной сессии (несколько сотен вложений) это не критично, но на очень
// долгой сессии (день+ без перезагрузки вкладки, активная переписка с медиа)
// давало неограниченный рост памяти. Map хранит порядок вставки, поэтому
// эвикция "выкинуть самый старый ключ" не требует отдельной структуры данных.
export function createLruMap(limit){
  const map = new Map();
  return {
    has: (key) => map.has(key),
    get: (key) => map.get(key),
    // set() всегда переставляет ключ в конец (самый свежий) - это касается и
    // повторной записи уже существующего ключа, и "трогания" при обращении
    // через touch().
    set(key, value){
      map.delete(key);
      map.set(key, value);
      if(map.size > limit){
        const oldest = map.keys().next().value;
        map.delete(oldest);
      }
      return value;
    },
    // Обновить позицию ключа в LRU-очереди без изменения значения - вызывать
    // при чтении из кэша (cache hit), иначе часто используемые записи всё
    // равно вымоются, если их давно не перезаписывали.
    touch(key){
      if(!map.has(key)) return;
      const value = map.get(key);
      map.delete(key);
      map.set(key, value);
    },
    delete: (key) => map.delete(key),
    get size(){ return map.size; },
  };
}
